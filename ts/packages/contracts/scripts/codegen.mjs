// @ts-check
// Regenerates src/abis/ and src/calls/ from the forge artifacts in
// solidity/out. Run `forge build` in solidity/ first.
//
// src/abis/ holds each contract's full ABI, emitted `as const satisfies Abi` so
// viem infers argument and return types. src/calls/ holds one call builder per
// state-changing function. Both are gitignored; run this before `pnpm build`.

import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { bindRoute } from './bind-route.mjs'

/** @typedef {import('viem').Abi} Abi */
/** @typedef {import('viem').AbiFunction} AbiFunction */
/** @typedef {Extract<Abi[number], { type: 'error' }>} AbiError */

/**
 * A forge build artifact, read for its ABI.
 * @typedef {{ abi: Abi }} ForgeArtifact
 */

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = resolve(packageDir, '..', '..', '..')
const outDir = join(repoRoot, 'solidity', 'out')
const abisDir = join(packageDir, 'src', 'abis')
const callsDir = join(packageDir, 'src', 'calls')

// Every contract the package ships an ABI for. `file` is the source unit under
// solidity/out, `name` the contract inside it, `exportName` what a consumer
// imports.
const contracts = [
  { file: 'IdentityRegistry.sol', name: 'IdentityRegistry', exportName: 'identityRegistryAbi' },
  { file: 'HandleResolver.sol', name: 'HandleResolver', exportName: 'handleResolverAbi' },
  { file: 'HandleEscrow.sol', name: 'HandleEscrow', exportName: 'handleEscrowAbi' },
  { file: 'NotaryService.sol', name: 'NotaryService', exportName: 'notaryServiceAbi' },
  {
    file: 'CeremonyProofVerifier.sol',
    name: 'CeremonyProofVerifier',
    exportName: 'ceremonyProofVerifierAbi',
  },
  { file: 'GoogleJwtRoots.sol', name: 'GoogleJwtRoots', exportName: 'googleJwtRootsAbi' },
  // An interface that carries the payload structs into an ABI.
  {
    file: 'ICeremonyPayloads.sol',
    name: 'ICeremonyPayloads',
    exportName: 'ceremonyPayloadsAbi',
  },
  // The errors bb's Honk verifiers raise.
  {
    file: 'IHonkVerifierErrors.sol',
    name: 'IHonkVerifierErrors',
    exportName: 'honkVerifierErrorsAbi',
  },
  { file: 'LibidFactory.sol', name: 'LibidFactory', exportName: 'libidFactoryAbi' },
  { file: 'WTIA9.sol', name: 'WTIA9', exportName: 'wtia9Abi' },
]

/**
 * @param {string} file
 * @param {string} name
 * @returns {ForgeArtifact}
 */
function readArtifact(file, name) {
  const artifactPath = join(outDir, file, `${name}.json`)
  try {
    return JSON.parse(readFileSync(artifactPath, 'utf8'))
  } catch (err) {
    console.error(`ERROR: cannot read ${artifactPath} — run \`forge build\` in solidity/ first`)
    throw err
  }
}

/// The errors of every contract on the bind route, each signature once.
function bindErrors() {
  /** @type {Map<string, AbiError>} */
  const bySignature = new Map()
  for (const [file, name] of bindRoute) {
    for (const entry of readArtifact(file, name).abi) {
      if (entry.type !== 'error') continue
      const signature = `${entry.name}(${entry.inputs.map((i) => i.type).join(',')})`
      if (!bySignature.has(signature)) bySignature.set(signature, entry)
    }
  }
  return [...bySignature.values()]
}

/** @param {string} source */
const banner = (source) =>
  `// Generated by ts/packages/contracts/scripts/codegen.mjs. Do not edit.\n// Source artifact: solidity/out/${source}\n`

// The ABIs keep forge's `internalType`: viem ignores it, and it names the
// struct behind each tuple.
/**
 * @param {string} abisTarget
 * @param {string} callsTarget
 */
function generate(abisTarget, callsTarget) {
  mkdirSync(abisTarget, { recursive: true })
  mkdirSync(callsTarget, { recursive: true })
  /** @type {{ moduleName: string, exportName: string }[]} */
  const moduleNames = []
  /** @type {string[]} */
  const callModules = []

  for (const { file, name, exportName } of contracts) {
    const artifact = readArtifact(file, name)

    const moduleName = exportName.replace(/Abi$/, '')
    moduleNames.push({ moduleName, exportName })

    const body = JSON.stringify(artifact.abi, null, 2)
    const content = `${banner(`${file}/${name}.json`)}
import type { Abi } from 'viem'

export const ${exportName} = ${body} as const satisfies Abi
`
    writeFileSync(join(abisTarget, `${moduleName}.ts`), content)

    const calls = callModule({ file, name, exportName, moduleName, abi: artifact.abi })
    if (calls) {
      writeFileSync(join(callsTarget, `${moduleName}.ts`), calls)
      callModules.push(moduleName)
    }
  }

  const route = bindRoute.map(([file, name]) => `${file}/${name}.json`).join(', ')
  writeFileSync(
    join(abisTarget, 'bindErrors.ts'),
    `${banner(route)}
import type { Abi } from 'viem'

/// Every error a \`bind\` can revert with, each signature once.
export const bindErrorsAbi = ${JSON.stringify(bindErrors(), null, 2)} as const satisfies Abi
`,
  )
  moduleNames.push({ moduleName: 'bindErrors', exportName: 'bindErrorsAbi' })

  const index = `${banner('*')}${moduleNames
    .map(({ moduleName, exportName }) => `export { ${exportName} } from './${moduleName}.js'`)
    .join('\n')}\n`
  writeFileSync(join(abisTarget, 'index.ts'), index)

  // Namespaced by contract: names such as `initialize` repeat across contracts.
  const callsIndex = `${banner('*')}${callModules
    .map((m) => `export * as ${m} from './${m}.js'`)
    .join('\n')}\n`
  writeFileSync(join(callsTarget, 'index.ts'), callsIndex)

  return { abis: moduleNames.length, calls: callModules.length }
}

/// One builder per state-changing function, or null when the contract has none.
///
/// `ContractFunctionArgs` reads the arguments off the ABI and resolves an
/// overload set to a union of tuples.
///
/// Payable functions take `value` before their arguments, so a missing value on
/// a payable write, or a value on a nonpayable one, fails to compile.
/**
 * @param {{ file: string, name: string, exportName: string, moduleName: string, abi: Abi }} target
 * @returns {string | null}
 */
function callModule({ file, name, exportName, moduleName, abi }) {
  const writes = abi.filter(
    /** @returns {entry is AbiFunction} */
    (entry) =>
      entry.type === 'function' &&
      entry.stateMutability !== 'view' &&
      entry.stateMutability !== 'pure',
  )
  if (writes.length === 0) return null

  // One builder per name: viem picks the overload from the arguments.
  /** @type {Map<string, boolean>} */
  const seen = new Map()
  for (const entry of writes) {
    // An overload set counts as payable only if every member is: otherwise
    // `value` would be required on a call that cannot accept it.
    seen.set(entry.name, (seen.get(entry.name) ?? true) && entry.stateMutability === 'payable')
  }

  const Pascal = moduleName[0].toUpperCase() + moduleName.slice(1)
  const fnType = `${Pascal}Fn`
  const argsType = `${Pascal}Args`
  const builders = [...seen.entries()].map(([fn, payable]) => {
    const params = payable
      ? `to: Address, value: bigint, ...args: ${argsType}<'${fn}'>`
      : `to: Address, ...args: ${argsType}<'${fn}'>`
    const fields = payable ? 'to,\n    value,' : 'to,'
    return `export function ${fn}(${params}): Call {
  return {
    ${fields}
    data: encodeFunctionData({ abi: ${exportName}, functionName: '${fn}', args }),
  }
}`
  })

  return `${banner(`${file}/${name}.json`)}
import {
  type Address,
  type ContractFunctionArgs,
  type ContractFunctionName,
  encodeFunctionData,
} from 'viem'

import type { Call } from '../call.js'
import { ${exportName} } from '../abis/${moduleName}.js'

type Mutability = 'nonpayable' | 'payable'
type ${fnType} = ContractFunctionName<typeof ${exportName}, Mutability>
type ${argsType}<F extends ${fnType}> = ContractFunctionArgs<typeof ${exportName}, Mutability, F>

${builders.join('\n\n')}
`
}

if (process.argv.length > 2) {
  console.error(`unknown argument: ${process.argv[2]}`)
  process.exit(2)
}

rmSync(abisDir, { recursive: true, force: true })
rmSync(callsDir, { recursive: true, force: true })
const counts = generate(abisDir, callsDir)

// biome decides where the generated lines break.
const biome = join(repoRoot, 'ts', 'node_modules', '.bin', 'biome')
if (!existsSync(biome)) {
  console.error(`ERROR: ${biome} not found — run \`pnpm -C ts install\` first`)
  process.exit(1)
}
// cwd is ts/: biome walks upward for its configuration and finds two roots
// from anywhere above it.
execFileSync(biome, ['format', '--write', abisDir, callsDir], {
  cwd: join(repoRoot, 'ts'),
  stdio: 'inherit',
})

console.log(`wrote ${counts.abis + 1} files to src/abis/, ${counts.calls + 1} to src/calls/`)
