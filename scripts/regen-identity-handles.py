#!/usr/bin/env python3
"""Regenerate the identity platform table, the refusals and the vector tables.

The sources are the pinned libID-circuits release's `platforms.json` (each
platform's tags, buffers and id shape) and `handles.json` (the vectors),
vendored into `solidity/contracts/circuits/` by
`scripts/vendor-circuit-verifiers.sh`. Run this script after the pin moves.
It writes:

    rust/identity/src/platforms.rs                  # Rust platform table + refusals
    rust/identity/src/vectors.rs                    # Rust vectors (tests, `test-helpers`)
    ts/packages/contracts/src/identity/platforms.ts # TypeScript platform table + refusals
    ts/packages/contracts/src/identity/vectors.ts   # TypeScript vectors (tests)

The refusals are handles.json's `errors`, worded per subject by `WORDING`.
Every handleNode and idNode is recomputed with hashlib and must match. The
transform (the token check and the fold) is hand written in Rust, TypeScript
and Noir. Solidity reads the tags from `CeremonyProfile`, folds in
`HandleNode`, and its tests read handles.json directly.

Run: ./scripts/regen-identity-handles.py [--check]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys
from dataclasses import dataclass
from typing import Any

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
SOLIDITY_ROOT = REPO_ROOT / "solidity"
VENDORED = SOLIDITY_ROOT / "contracts" / "circuits"
SOURCE = VENDORED / "handles.json"
PLATFORMS = VENDORED / "platforms.json"
RUST_SRC = REPO_ROOT / "rust" / "identity" / "src"
TS_SRC = REPO_ROOT / "ts" / "packages" / "contracts" / "src" / "identity"

BANNER = [
    "Generated by scripts/regen-identity-handles.py. Do not edit.",
    "The sources are the pinned libID-circuits release's platforms.json and handles.json,",
    "vendored into solidity/contracts/circuits/ by scripts/vendor-circuit-verifiers.sh.",
]


def header(comment: str) -> str:
    return "".join(f"{comment} {line}\n" for line in BANNER)


@dataclass(frozen=True)
class Platform:
    """One platform of platforms.json: its node tags and the circuits' buffers."""

    key: str
    max_length: int
    user_id_tag: str
    handle_tag: str
    max_id: int
    id_shape: str

    @classmethod
    def from_json(cls, raw: dict[str, Any]) -> Platform:
        return cls(
            key=raw["platform"],
            max_length=raw["maxHandle"],
            user_id_tag=raw["userIdTag"],
            handle_tag=raw["handleTag"],
            max_id=raw["maxId"],
            id_shape=raw["idShape"],
        )

    @property
    def decimal(self) -> bool:
        """Whether its ids are ASCII digits."""
        return self.id_shape == "decimal"


@dataclass(frozen=True)
class ErrorKind:
    """One refusal of handles.json `errors`; its index is its kind."""

    key: str
    note: str

    @classmethod
    def from_json(cls, raw: dict[str, Any]) -> ErrorKind:
        return cls(key=raw["key"], note=raw["note"])


@dataclass(frozen=True)
class HandleVector:
    """One case of handles.json `vectors`: accepted when it has an output."""

    platform: str
    input: str
    output: str | None
    error: str | None
    handle_node: str | None

    @classmethod
    def from_json(cls, raw: dict[str, Any]) -> HandleVector:
        return cls(
            platform=raw["platform"],
            input=raw["input"],
            output=raw.get("output"),
            error=raw.get("error"),
            handle_node=raw.get("handleNode"),
        )

    @property
    def accepted(self) -> bool:
        return self.output is not None


@dataclass(frozen=True)
class IdVector:
    """One case of handles.json `idVectors`: accepted when it names no error."""

    platform: str
    input: str
    error: str | None
    id_node: str | None

    @classmethod
    def from_json(cls, raw: dict[str, Any]) -> IdVector:
        return cls(
            platform=raw["platform"],
            input=raw["input"],
            error=raw.get("error"),
            id_node=raw.get("idNode"),
        )

    @property
    def accepted(self) -> bool:
        return self.error is None


@dataclass(frozen=True)
class Table:
    """handles.json, with the platforms of platforms.json."""

    platforms: list[Platform]
    errors: list[ErrorKind]
    vectors: list[HandleVector]
    id_vectors: list[IdVector]

    @classmethod
    def from_json(cls, handles: dict[str, Any], platforms: dict[str, Any]) -> Table:
        return cls(
            platforms=[Platform.from_json(p) for p in platforms["platforms"]],
            errors=[ErrorKind.from_json(e) for e in handles["errors"]],
            vectors=[HandleVector.from_json(v) for v in handles["vectors"]],
            id_vectors=[IdVector.from_json(v) for v in handles["idVectors"]],
        )

    def check_refusals(self) -> None:
        """Refuse a table whose refusals `WORDING` does not word, in order, or
        whose refused vectors name a refusal the table does not list."""
        keys = [err.key for err in self.errors]
        if keys != [wording.key for wording in WORDING]:
            raise SystemExit(f"ERROR: handles.json errors {keys} are not the ones WORDING words")
        for vec in [*self.vectors, *self.id_vectors]:
            if vec.error is not None and vec.error not in keys:
                raise SystemExit(f"ERROR: unknown error kind {vec.error!r} in a vector")
            if vec.error is None and not vec.accepted:
                raise SystemExit(f"ERROR: {vec.platform} {vec.input!r} has neither an output nor an error")


@dataclass(frozen=True)
class Wording:
    """What one refusal of handles.json `errors` says about a handle and about an id.

    `handle_note` replaces the refusal's handles.json `note` in the handle
    error's doc where the shared note also words ids."""

    key: str
    handle: str
    id: str
    handle_note: str | None = None


# The refusal messages, in handles.json `errors` order. Rust's Display and the
# TypeScript error messages are generated from these.
WORDING = (
    Wording("Empty", "the handle is empty", "the id is empty"),
    Wording("TooLong", "the handle is too long for this platform", "the id is too long for this platform"),
    Wording(
        "BadCharacter",
        "the handle has a byte outside printable ASCII, or a quote or backslash",
        "the id has a byte this platform does not allow",
        "A byte outside printable ASCII, a quote or a backslash.",
    ),
)


@dataclass(frozen=True)
class Subject:
    """What a refusal is about, and the error type that carries it."""

    rust_type: str
    ts_type: str
    ts_message: str
    doc: str
    is_handle: bool

    def message(self, wording: Wording) -> str:
        return wording.handle if self.is_handle else wording.id

    def note(self, err: ErrorKind, wording: Wording) -> str:
        return wording.handle_note if self.is_handle and wording.handle_note else err.note


SUBJECTS = (
    Subject("HandleError", "HandleError", "handleRefusal", "Why a handle was refused.", True),
    Subject("IdError", "IdError", "idRefusal", "Why no circuit would hash an id.", False),
)


def fold_byte(b: int) -> int:
    """A-Z down to a-z; every other byte unchanged."""
    return b + 0x20 if 0x41 <= b <= 0x5A else b


def check_nodes(table: Table) -> None:
    """Refuse a table whose accepted outputs are not the fold of their inputs,
    or whose stored nodes are not SHA256(tag || value); a refused vector
    carries no node."""
    tags = {p.key: p for p in table.platforms}
    for vec in table.vectors:
        folded = bytes(fold_byte(b) for b in vec.input.encode())
        if vec.output is not None and vec.output.encode() != folded:
            raise SystemExit(
                f"ERROR: {vec.platform} {vec.input!r}: output {vec.output!r} is not its input folded"
            )
    cases = [(vec, tags[vec.platform].handle_tag, "handleNode", vec.output, vec.handle_node) for vec in table.vectors]
    cases += [
        (vec, tags[vec.platform].user_id_tag, "idNode", vec.input if vec.accepted else None, vec.id_node)
        for vec in table.id_vectors
    ]
    for vec, tag, field, value, node in cases:
        if value is None:
            if node is not None:
                raise SystemExit(f"ERROR: refused {vec.platform} {vec.input!r} carries {field}")
            continue
        want = "0x" + hashlib.sha256((tag + value).encode()).hexdigest()
        if node != want:
            raise SystemExit(
                f"ERROR: {vec.platform} {vec.input!r}: {field} is not "
                f"SHA256(tag || value); expected {want}"
            )


def rust_escape(value: str) -> str:
    """Rust string literal.

    Rust writes a code point as `\\u{e9}`, not as JSON's `\\u00e9`, so the
    escapes cannot be borrowed from `json.dumps` unchanged.
    """
    out = []
    for ch in value:
        if ch in ('"', "\\"):
            out.append("\\" + ch)
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20 or ord(ch) > 0x7E:
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(ch)
    return "".join(out)


def rust_platforms(table: Table) -> str:
    """The platform table and the refusals: what libid-identity ships."""
    platforms = table.platforms
    lines = [
        header("//").rstrip("\n"),
        "",
        "//! The platform table: each platform's key, node tags and buffers, and the",
        "//! refusals the handle and id checks share.",
        "",
        "use std::{",
        "    error::Error,",
        "    fmt,",
        "};",
        "",
        "/// A platform: its key, node tags and buffers.",
        "pub struct Platform {",
        "    /// keccak256 of this string is the platform id.",
        "    pub key: &'static str,",
        "    /// An id node is SHA256 of this tag, then the id.",
        "    pub user_id_tag: &'static str,",
        "    /// A handle node is SHA256 of this tag, then the normalized handle.",
        "    pub handle_tag: &'static str,",
        "    /// How long a handle may be.",
        "    pub rules: crate::Rules,",
        "    /// How long an id may be, and whether it is a number.",
        "    pub id_rules: crate::IdRules,",
        "}",
        "",
    ]
    for p in platforms:
        lines.append("/// keccak256 of this string is the platform id.")
        lines.append(f'pub const PLATFORM_{p.key.upper()}_KEY: &str = "{p.key}";')
    lines.append("")
    for p in platforms:
        name = p.key.upper()
        lines += [
            f"/// The {p.key} platform.",
            f"pub const PLATFORM_{name}: Platform = Platform {{",
            f"    key: PLATFORM_{name}_KEY,",
            f'    user_id_tag: "{p.user_id_tag}",',
            f'    handle_tag: "{p.handle_tag}",',
            "    rules: crate::Rules {",
            f"        max_length: {p.max_length},",
            "    },",
            "    id_rules: crate::IdRules {",
            f"        max_length: {p.max_id},",
            f"        decimal: {str(p.decimal).lower()},",
            "    },",
            "};",
        ]
    lines += [
        "",
        "/// Every platform, in table order.",
        f"pub static PLATFORMS: [Platform; {len(platforms)}] = ["
        + ", ".join(f"PLATFORM_{p.key.upper()}" for p in platforms)
        + "];",
        "",
        "/// The platform with this key, if the table names it.",
        "pub fn platform(key: &str) -> Option<&'static Platform> {",
        "    PLATFORMS.iter().find(|p| p.key == key)",
        "}",
    ]
    for subject in SUBJECTS:
        lines += [
            "",
            f"/// {subject.doc}",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
            f"pub enum {subject.rust_type} {{",
        ]
        for err, wording in zip(table.errors, WORDING):
            lines += [f"    /// {subject.note(err, wording)}", f"    {err.key},"]
        lines += [
            "}",
            "",
            f"impl fmt::Display for {subject.rust_type} {{",
            "    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {",
            "        f.write_str(match self {",
        ]
        for wording in WORDING:
            lines.append(f'            Self::{wording.key} => "{subject.message(wording)}",')
        lines += [
            "        })",
            "    }",
            "}",
            "",
            f"impl Error for {subject.rust_type} {{}}",
        ]
    return "\n".join(lines) + "\n"


def rust_vectors(table: Table) -> str:
    """The vector tables: what the tests of libid-identity and its consumers run."""
    lines = [
        header("//").rstrip("\n"),
        "",
        "//! The shared handle and id vector tables every language runs.",
        "",
        "use crate::{",
        "    HandleError,",
        "    IdError,",
        "};",
        "",
        "/// An accepted handle: its folded form and its node.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct Folded {",
        "    /// The handle with A-Z folded to a-z.",
        "    pub handle: &'static str,",
        "    /// SHA256(handle tag || handle), hex.",
        "    pub node: &'static str,",
        "}",
        "",
        "/// One handle case from the shared table.",
        "pub struct Vector {",
        "    /// Platform key, as written in the source table.",
        "    pub platform: &'static str,",
        "    /// The handle exactly as a caller supplied it.",
        "    pub input: &'static str,",
        "    /// The folded handle and its node, or the refusal.",
        "    pub expected: Result<Folded, HandleError>,",
        "}",
        "",
        "/// One id case from the shared table.",
        "pub struct IdVector {",
        "    /// Platform key, as written in the source table.",
        "    pub platform: &'static str,",
        "    /// The id exactly as the platform sent it.",
        "    pub input: &'static str,",
        "    /// SHA256(id tag || input), hex, or the refusal.",
        "    pub expected: Result<&'static str, IdError>,",
        "}",
        "",
        "/// Every handle case, shared with Solidity, TypeScript and Noir.",
        f"pub const VECTORS: [Vector; {len(table.vectors)}] = [",
    ]
    for vec in table.vectors:
        if vec.output is not None:
            expected = f'Ok(Folded {{ handle: "{rust_escape(vec.output)}", node: "{vec.handle_node}" }})'
        else:
            expected = f"Err(HandleError::{vec.error})"
        lines += [
            "    Vector {",
            f'        platform: "{vec.platform}",',
            f'        input: "{rust_escape(vec.input)}",',
            f"        expected: {expected},",
            "    },",
        ]
    lines += [
        "];",
        "",
        "/// Every id case, shared with TypeScript and Noir.",
        f"pub const ID_VECTORS: [IdVector; {len(table.id_vectors)}] = [",
    ]
    for vec in table.id_vectors:
        expected = f'Ok("{vec.id_node}")' if vec.accepted else f"Err(IdError::{vec.error})"
        lines += [
            "    IdVector {",
            f'        platform: "{vec.platform}",',
            f'        input: "{rust_escape(vec.input)}",',
            f"        expected: {expected},",
            "    },",
        ]
    lines.append("];")
    return "\n".join(lines) + "\n"


def ts_platforms(table: Table) -> str:
    """The platform table and the refusals: what @libid/contracts ships."""
    platforms = table.platforms
    lines = [
        header("//").rstrip("\n"),
        "",
        "/// The platform table: each platform's key, node tags and buffers, and the",
        "/// refusals the handle and id checks share.",
        "",
        "import type { Rules } from './handle.js'",
        "import type { IdRules } from './node.js'",
        "",
        "/** A platform: its key, node tags and buffers. */",
        "export interface Platform {",
        "  /** keccak256 of this string is the platform id. */",
        "  key: string",
        "  /** An id node is SHA256 of this tag, then the id. */",
        "  userIdTag: string",
        "  /** A handle node is SHA256 of this tag, then the normalized handle. */",
        "  handleTag: string",
        "  rules: Rules",
        "  idRules: IdRules",
        "}",
        "",
    ]
    for p in platforms:
        lines.append("/** keccak256 of this string is the platform id. */")
        lines.append(f"export const PLATFORM_{p.key.upper()}_KEY = '{p.key}'")
    lines.append("")
    for p in platforms:
        name = p.key.upper()
        lines += [
            f"export const PLATFORM_{name}: Platform = {{",
            f"  key: PLATFORM_{name}_KEY,",
            f"  userIdTag: '{p.user_id_tag}',",
            f"  handleTag: '{p.handle_tag}',",
            "  rules: {",
            f"    maxLength: {p.max_length},",
            "  },",
            "  idRules: {",
            f"    maxLength: {p.max_id},",
            f"    decimal: {str(p.decimal).lower()},",
            "  },",
            "}",
        ]
    lines += [
        "",
        "/** Every platform, in table order. */",
        "export const PLATFORMS: readonly Platform[] = ["
        + ", ".join(f"PLATFORM_{p.key.upper()}" for p in platforms)
        + "]",
        "",
        "/** The platform with this key, if the table names it. */",
        "export function platform(key: string): Platform | undefined {",
        "  return PLATFORMS.find((p) => p.key === key)",
        "}",
        "",
        "/** Which refusal a handle or an id met, as the shared table names it. */",
        "export type RefusalKind = " + " | ".join(f"'{err.key}'" for err in table.errors),
    ]
    for subject in SUBJECTS:
        lines += [
            "",
            f"/** {subject.doc} */",
            f"export class {subject.ts_type} extends Error {{",
            "  constructor(readonly kind: RefusalKind) {",
            f"    super({subject.ts_message}(kind))",
            f"    this.name = '{subject.ts_type}'",
            "  }",
            "}",
            "",
            f"function {subject.ts_message}(kind: RefusalKind): string {{",
            "  switch (kind) {",
        ]
        for wording in WORDING:
            lines += [f"    case '{wording.key}':", f"      return '{subject.message(wording)}'"]
        lines += ["  }", "}"]
    return "\n".join(lines) + "\n"


def ts_vectors(table: Table) -> str:
    """The vector tables the TypeScript tests run."""
    lines = [
        header("//").rstrip("\n"),
        "",
        "/// The shared handle and id vector tables every language runs.",
        "",
        "import type { RefusalKind } from './platforms.js'",
        "",
        "/** What the transform answers for a handle: its folded form and node, or the refusal. */",
        "export type HandleExpected =",
        "  | { ok: true; handle: string; handleNode: string }",
        "  | { ok: false; refusal: RefusalKind }",
        "",
        "/** What the id check answers: the id node, or the refusal. */",
        "export type IdExpected = { ok: true; idNode: string } | { ok: false; refusal: RefusalKind }",
        "",
        "export interface HandleVector {",
        "  platform: string",
        "  /** The handle exactly as a caller supplied it. */",
        "  input: string",
        "  expected: HandleExpected",
        "}",
        "",
        "export interface IdVector {",
        "  platform: string",
        "  /** The id exactly as the platform sent it. */",
        "  input: string",
        "  expected: IdExpected",
        "}",
        "",
        "export const HANDLE_VECTORS: readonly HandleVector[] = [",
    ]
    for vec in table.vectors:
        if vec.output is not None:
            expected = (
                f"{{ ok: true, handle: {json.dumps(vec.output)}, handleNode: {json.dumps(vec.handle_node)} }}"
            )
        else:
            expected = f"{{ ok: false, refusal: {json.dumps(vec.error)} }}"
        lines.append(
            f"  {{ platform: {json.dumps(vec.platform)}, input: {json.dumps(vec.input)}, expected: {expected} }},"
        )
    lines += ["]", "", "export const ID_VECTORS: readonly IdVector[] = ["]
    for vec in table.id_vectors:
        if vec.accepted:
            expected = f"{{ ok: true, idNode: {json.dumps(vec.id_node)} }}"
        else:
            expected = f"{{ ok: false, refusal: {json.dumps(vec.error)} }}"
        lines.append(
            f"  {{ platform: {json.dumps(vec.platform)}, input: {json.dumps(vec.input)}, expected: {expected} }},"
        )
    lines.append("]")
    return "\n".join(lines) + "\n"


def display(path: pathlib.Path) -> str:
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Write nothing; exit non-zero if any generated file is out of date.",
    )
    args = parser.parse_args()

    for path in (SOURCE, PLATFORMS):
        if not path.exists():
            print(
                f"ERROR: {display(path)} is missing; run scripts/vendor-circuit-verifiers.sh",
                file=sys.stderr,
            )
            return 1
    # handles.json holds non-ASCII, so decode it as UTF-8 whatever the locale.
    raw = SOURCE.read_bytes()
    table = Table.from_json(
        json.loads(raw.decode("utf-8")),
        json.loads(PLATFORMS.read_text(encoding="utf-8")),
    )
    table.check_refusals()
    check_nodes(table)

    outputs = [
        (RUST_SRC / "platforms.rs", rust_platforms(table)),
        (RUST_SRC / "vectors.rs", rust_vectors(table)),
        (TS_SRC / "platforms.ts", ts_platforms(table)),
        (TS_SRC / "vectors.ts", ts_vectors(table)),
    ]

    if args.check:
        stale = [
            path
            for path, text in outputs
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            print("ERROR: generated files are out of date. Run scripts/regen-identity-handles.py", file=sys.stderr)
            for path in stale:
                print(f"  {display(path)}", file=sys.stderr)
            return 1
        print("generated files are up to date")
        return 0

    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {display(path)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
