#!/usr/bin/env python3
"""Regenerate the identity platform constants and the handle vector table.

The sources are each platform's `keys` in
`solidity/contracts/ceremony/profiles.json` (tags and the circuits' buffers)
and the vectors in `solidity/contracts/handles/handles.json`. Edit them, then
run this script. These files are written and never drift apart:

    rust/identity/src/handle_vectors.rs                    # Rust constants + vectors
    ts/packages/contracts/src/identity/handleVectors.ts    # TypeScript constants + vectors
    <libid-circuits>/lib/identity/src/table.nr             # Noir constants, with --noir-out <that path>
    <libid-circuits>/lib/identity/src/table_tests.nr       # Noir vector tests, beside it

Every output carries the SHA-256 of handles.json followed by profiles.json.
Every handleNode and idNode in the table is recomputed with hashlib and must
match. The transform (the token check and the fold) is hand written in Rust,
TypeScript and Noir; Solidity reads the tags from `CeremonyProfile` and folds
in `HandleNode`, and its tests read handles.json directly.

Run: ./scripts/regen-identity-handles.py [--noir-out ../libid-circuits/lib/identity/src/table.nr]
"""
