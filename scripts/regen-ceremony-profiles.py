def sol_doc(note: Note, indent: str = "    ") -> list[str]:
    lines = as_lines(note)
    if not lines:
        return []
    out = [f"{indent}/// @dev {lines[0]}"]
    out += [f"{indent}///      {line}" if line else f"{indent}///" for line in lines[1:]]
    return out


def gen_sol(spec: Spec) -> str:
    profiles = spec.profiles
    versions = {p.ceremony_version for p in profiles}
    if len(versions) != 1:
        raise SystemExit("ERROR: the Solidity LAUNCH_VERSION assumes one version for all profiles")
    launch_version = versions.pop()

    lines = [
        "// SPDX-License-Identifier: MIT",
        "pragma solidity ^0.8.24;",
        "",
        header("//").rstrip("\n"),
        f"// Node tags come from {PLATFORMS_REL}, vendored from the pinned libID-circuits release.",
        "",
        "/// @title CeremonyProfile",
        "/// @notice The tags a Platform Verifier pins, and the validity window",
        "///         each profile fixes.",
        "///",
    ]
    lines += [f"/// {line}" if line else "///" for line in as_lines(spec.note, width=70)]
    lines += [
        "library CeremonyProfile {",
        "    // --- Platform identifiers -----------------------------------------------",
        "",
    ]
    for profile in profiles:
        name = upper(profile.platform)
        lines.append(
            f'    bytes32 internal constant PLATFORM_{name} = keccak256(bytes("{profile.platform}"));'
        )

    lines += [
        "",
        "    // --- Node tags ----------------------------------------------------------",
        "",
        "    /// @dev A node is SHA256 of its tag, then the id or the folded handle.",
    ]
    for profile in profiles:
        name = upper(profile.platform)
        tags = profile.tags
        lines.append(f'    bytes internal constant {name}_USER_ID_TAG = "{tags.user_id}";')
        lines.append(f'    bytes internal constant {name}_HANDLE_TAG = "{tags.handle}";')

    lines += [
        "",
        "    // --- Authorities --------------------------------------------------------",
        "",
        "    /// @dev keccak256 of the lowercase TLS server name, no trailing dot, that",
        "    ///      the notary authenticated. The verifier reads it from `authorityId`,",
        "    ///      never from the prover-composed `Host` header (REQ-COMMON-21,",
        "    ///      REQ-COMMON-21A).",
        "",
    ]
    for suffix, host in authorities(spec):
        lines.append(
            f'    bytes32 internal constant AUTHORITY_{suffix} = keccak256(bytes("{host}"));'
        )

    lines += [
        "",
        "    // --- Sessions -------------------------------------------------------------",
        "",
        "    /// @dev The request-line prefix each session sends, trailing space included.",
        "    ///      The space stops `GET /user` from prefixing `GET /users/me`.",
        "",
    ]
    for profile in profiles:
        name = upper(profile.platform)
        for session in profile.sessions:
            const = f"{name}_{upper(session.KIND)}_REQUEST_LINE"
            lines.append(f'    bytes internal constant {const} = "{session.request_line}";')

    lines += [
        "",
        "    /// @dev The header lines each request must carry exactly once: `host`",
        "    ///      naming the pinned authority and, on the token request, the",
        "    ///      `content-type` that selects the platform's parser (REQ-COMMON-21B).",
        "",
    ]
    for profile in profiles:
        for session in profile.sessions:
            const = f"{upper(profile.platform)}_{upper(session.KIND)}_REQUIRED_HEADERS"
            lines.append(f'    bytes internal constant {const} = "{escaped(crlf(required_headers(session)))}";')

    lines += [
        "",
        "    /// @dev The token request body's form fields in serialization order,",
        "    ///      joined by `&`. `requireExactForm` holds the body to exactly these",
        "    ///      names in this order, each once with a nonempty value. GitHub's",
        "    ///      list is REQ-PLAT-61's and X's is REQ-PLAT-63's.",
        "",
    ]
    for profile in profiles:
        token = profile.token
        if token is None:
            continue
        const = f"{upper(profile.platform)}_TOKEN_FIELDS"
        lines.append(f'    bytes internal constant {const} = "{"&".join(token_fields(token))}";')

    lines += [""]
    lines += sol_doc(spec.requests.note)
    lines.append(
        f'    bytes internal constant FORBIDDEN_REQUEST_HEADERS = "{escaped(crlf(forbidden_headers(spec)))}";'
    )
    lines += [
        "",
        "    /// @dev Whether `nameHash` is the keccak256 of a name",
        "    ///      `FORBIDDEN_REQUEST_HEADERS` lists.",
        "    function isForbiddenRequestHeader(bytes32 nameHash) internal pure returns (bool) {",
        "        return "
        + " || ".join(f'nameHash == keccak256("{name}")' for name in forbidden_headers(spec))
        + ";",
        "    }",
    ]

    lines += [
        "",
        "    /// @dev The two identity members a Platform Verifier finds as",
        "    ///      commitments by their revealed anchors (REQ-PLAT-51).",
        "",
    ]
    for profile in profiles:
        identity = profile.identity
        if identity is None:
            continue
        name = upper(profile.platform)
        lines.append(f'    string internal constant {name}_ID_FIELD = "{identity.id_field}";')
        lines.append(
            f'    string internal constant {name}_HANDLE_FIELD = "{identity.handle_field}";'
        )

    lines += [
        "",
        "    // --- Validity -------------------------------------------------------------",
        "",
    ]
    lines += sol_doc(VALIDITY_NOTE)
    for profile in profiles:
        lines.append("")
        lines += [f"    // {line}" if line else "    //" for line in as_lines(profile.validity.note)]
        for const, value, _ in validity_constants(profile):
            lines.append(f"    uint64 internal constant {const} = {value};")

    lines += [
        "",
        "    // --- Launch profile shape ------------------------------------------------",
        "",
        "    /// @dev Launch profiles are "
        + ", ".join(f"`{p.platform}/v{p.ceremony_version}`" for p in profiles)
        + "",
        "    ///      (REQ-PLAT-01).",
        f"    uint16 internal constant LAUNCH_VERSION = {launch_version};",
        "",
        "    /// @dev The attestations a submission carries, one per session of the",
        "    ///      profile (REQ-COMMON-41).",
        "    function attestationCount(bytes32 platformId) internal pure returns (uint8) {",
    ]
    by_count: dict[int, list[str]] = {}
    for profile in profiles:
        by_count.setdefault(len(profile.sessions), []).append(upper(profile.platform))
    for count in sorted(by_count):
        test = " || ".join(f"platformId == PLATFORM_{name}" for name in by_count[count])
        lines.append(f"        if ({test}) return {count};")
    lines += [
        "        revert UnknownPlatform(platformId);",
        "    }",
        "",
    ]
    lines += sol_lookups(spec)
    lines += [
        "    error UnknownPlatform(bytes32 platformId);",
        "}",
        "",
    ]
    return "\n".join(lines)


def header_value(line: str) -> str:
    """A required line's value as a verifier reads it: after the colon, trimmed."""
    return line.split(":", 1)[1].strip(" \t")


def sol_lookups(spec: Spec) -> list[str]:
    """Lookups of the profile constants by platform id, called with a verifier's
    `_platform()`. A session lookup reverts for a platform without that
    session. A validity lookup returns zero where the profile fixes no value."""
    profiles = spec.profiles
    lines = [
        "    // --- By platform ----------------------------------------------------------",
        "",
    ]

    def lookup(name: str, returns: str, cases: list[tuple[str, str]], default: str | None, doc: str) -> None:
        lines.extend(sol_doc(textwrap.wrap(doc, width=72)))
        lines.append(f"    function {name}(bytes32 platformId) internal pure returns ({returns}) {{")
        for platform, value in cases:
            lines.append(f"        if (platformId == PLATFORM_{upper(platform)}) return {value};")
        if default is not None:
            known = [p.platform for p in profiles if p.platform not in {c for c, _ in cases}]
            if known:
                test = " || ".join(f"platformId == PLATFORM_{upper(k)}" for k in known)
                lines.append(f"        if ({test}) return {default};")
        lines.extend(["        revert UnknownPlatform(platformId);", "    }", ""])

    lines.append("    /// @dev Whether a profile names this platform.")
    lines.append("    function knows(bytes32 platformId) internal pure returns (bool) {")
    lines.append(
        "        return " + " || ".join(f"platformId == PLATFORM_{upper(p.platform)}" for p in profiles) + ";"
    )
    lines += ["    }", ""]
    lookup(
        "userIdTag",
        "bytes memory",
        [(p.platform, f"{upper(p.platform)}_USER_ID_TAG") for p in profiles],
        None,
        "The tag the platform's id nodes are hashed under.",
    )
    lookup(
        "handleTag",
        "bytes memory",
        [(p.platform, f"{upper(p.platform)}_HANDLE_TAG") for p in profiles],
        None,
        "The tag the platform's handle nodes are hashed under.",
    )
    lookup(
        "ceremonyVersion",
        "uint16",
        [(p.platform, str(p.ceremony_version)) for p in profiles],
        None,
        "The profile's ceremony version.",
    )
    for window in VALIDITY:
        stem = window.stem
        fn = stem.lower().split("_seconds")[0]
        fn = fn.split("_")[0] + "".join(w.capitalize() for w in fn.split("_")[1:])
        lookup(
            fn,
            "uint64",
            [(p.platform, f"{stem}_{upper(p.platform)}") for p in profiles if p.validity.seconds(window) is not None],
            "0",
            f"In seconds: {window.bounds}",
        )
    for session_name in SESSIONS:
        with_session = [(p.platform, s) for p in profiles if (s := p.session(session_name)) is not None]
        lookup(
            f"{session_name}Authority",
            "bytes32",
            [(p, f"AUTHORITY_{authority_name(sess.authority)}") for p, sess in with_session],
            None,
            f"The {session_name} session's authority.",
        )
        lookup(
            f"{session_name}RequestLine",
            "bytes memory",
            [(p, f"{upper(p)}_{upper(session_name)}_REQUEST_LINE") for p, _ in with_session],
            None,
            f"The {session_name} session's request-line prefix.",
        )
        # The hashes `_field` and `_hash` compute from each required line, so
        # no verifier parses the CRLF block at run time.
        lines.append(f"    /// @dev keccak256 of the name and trimmed value of each line of the")
        lines.append(f"    ///      platform's `*_{upper(session_name)}_REQUIRED_HEADERS`, in order.")
        lines.append(f"    function {session_name}RequiredHeaderHashes(bytes32 platformId)")
        lines += ["        internal", "        pure", "        returns (bytes32[] memory names, bytes32[] memory values)", "    {"]
        for platform, sess in with_session:
            required = required_headers(sess)
            lines.append(f"        if (platformId == PLATFORM_{upper(platform)}) {{")
            lines.append(f"            names = new bytes32[]({len(required)});")
            lines.append(f"            values = new bytes32[]({len(required)});")
            for i, line in enumerate(required):
                name = line.split(":", 1)[0]
                lines.append(
                    f'            (names[{i}], values[{i}]) = (keccak256("{name}"), keccak256("{header_value(line)}"));'
                )
            lines += ["            return (names, values);", "        }"]
        lines += ["        revert UnknownPlatform(platformId);", "    }", ""]
    lookup(
        "tokenFields",
        "bytes memory",
        [(p.platform, f"{upper(p.platform)}_TOKEN_FIELDS") for p in profiles if p.token is not None],
        None,
        "The token body's field list.",
    )
    lines.append("    /// @dev The identity members the commitments are framed by; `idIsInteger`")
    lines.append("    ///      for a bare JSON integer id, else a JSON string.")
    lines.append("    function identityFields(bytes32 platformId)")
    lines += [
        "        internal",
        "        pure",
        "        returns (string memory idField, bool idIsInteger, string memory handleField)",
        "    {",
    ]
    for p in profiles:
        identity = p.identity
        if identity is None:
            continue
        name = upper(p.platform)
        integer = "true" if identity.id_shape == "jsonInteger" else "false"
        lines.append(
            f"        if (platformId == PLATFORM_{name}) return ({name}_ID_FIELD, {integer}, {name}_HANDLE_FIELD);"
        )
    lines += ["        revert UnknownPlatform(platformId);", "    }", ""]
    return lines


def sol_formatted(source: str) -> str:
    """Run the repository's `forge fmt` over generated Solidity."""
    if shutil.which("forge") is None:
        print("ERROR: forge is required to format the generated Solidity", file=sys.stderr)
        raise SystemExit(1)
    done = subprocess.run(
        ["forge", "fmt", "--raw", "-"],
        input=source,
        capture_output=True,
        text=True,
        cwd=SOLIDITY_ROOT,
    )
    if done.returncode != 0:
        print(f"ERROR: forge fmt failed:\n{done.stderr}", file=sys.stderr)
        raise SystemExit(1)
    return done.stdout


