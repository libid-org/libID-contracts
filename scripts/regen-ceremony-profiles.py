def ts_str(value: str | None) -> str:
    if value is None:
        return "null"
    escaped = value.replace("\\", "\\\\").replace("'", "\\'")
    return f"'{escaped}'"


def ts_doc(note: Note, indent: str = "") -> list[str]:
    lines = as_lines(note)
    if not lines:
        return []
    out = [f"{indent}/**"]
    out += [f"{indent} * {line}" if line else f"{indent} *" for line in lines]
    out.append(f"{indent} */")
    return out


def ts_session(session: Session, indent: int) -> list[str]:
    pad = " " * indent
    return [
        f"{pad}session: {{",
        f'{pad}  authority: {ts_str(session.authority)},',
        f'{pad}  method: {ts_str(session.method)},',
        f'{pad}  path: {ts_str(session.path)},',
        f"{pad}  requestLine: {ts_str(session.request_line)},",
        f"{pad}}},",
    ]


@dataclass(frozen=True)
class BiomeConfig:
    """ts/biome.json, read for the formatter's line width."""

    line_width: int

    @classmethod
    def from_json(cls, raw: dict[str, Any]) -> BiomeConfig:
        return cls(line_width=int(raw.get("formatter", {}).get("lineWidth", 80)))


def ts_line_width() -> int:
    """The formatter's line width, read from its own config so the two agree."""
    config = REPO_ROOT / "ts" / "biome.json"
    if not config.exists():
        return 80
    return BiomeConfig.from_json(json.loads(config.read_text(encoding="utf-8"))).line_width


def ts_array(prefix: str, items: list[str], indent: str, suffix: str) -> list[str]:
    """`prefix[items]suffix` on one line when it fits, else one item per line.

    The formatter's rule, so a generated file passes `fmt:check` unformatted.
    """
    one = f"{indent}{prefix}[{', '.join(ts_str(item) for item in items)}]{suffix}"
    if len(one) <= ts_line_width():
        return [one]
    return [f"{indent}{prefix}[", *(f"{indent}  {ts_str(item)}," for item in items), f"{indent}]{suffix}"]


def gen_ts(spec: Spec) -> str:
    lines = [header("//").rstrip("\n"), ""]
    lines += ts_doc(spec.note)
    lines += [
        "",
        "/** Which shape a platform's immutable identifier takes in its response. */",
        "export type IdShape = 'jsonString' | 'jsonInteger'",
        "",
        "export interface Session {",
        "  /** The lowercase TLS server name the notary authenticates. */",
        "  readonly authority: string",
        "  readonly method: string",
        "  readonly path: string",
        "  /** The request-line prefix the verifier compares byte for byte. */",
        "  readonly requestLine: string",
        "}",
        "",
        "export interface TokenSession {",
        "  readonly session: Session",
        "  /** The header lines a Platform Verifier requires exactly once: `host`",
        "   * and `content-type`. Other headers pass unless",
        "   * `FORBIDDEN_REQUEST_HEADERS` names them. `content-length` is absent:",
        "   * the HTTP client writes it. */",
        "  readonly requiredHeaders: readonly string[]",
        "  /** The body's form fields in serialization order. Verifiers require",
        "   * exactly these names in this order, each once with a nonempty value.",
        "   * GitHub's list is REQ-PLAT-61's and X's is REQ-PLAT-63's. */",
        "  readonly tokenFields: readonly string[]",
        "}",
        "",
        "export interface IdentitySession {",
        "  readonly session: Session",
        "  /** The header lines a Platform Verifier requires exactly once: `host`. */",
        "  readonly requiredHeaders: readonly string[]",
        "  readonly idField: string",
        "  readonly idShape: IdShape",
        "  readonly handleField: string",
        "}",
        "",
        "export interface Profile {",
        "  /** The platform name. The platform id is its keccak256. */",
        "  readonly platform: string",
        "  readonly ceremonyVersion: number",
        "  readonly token: TokenSession | null",
        "  readonly identity: IdentitySession | null",
        "}",
        "",
    ]

    for profile in spec.profiles:
        name = upper(profile.platform)
        lines += ts_doc(profile.note)
        lines.append(f"export const {name}: Profile = {{")
        lines.append(f"  platform: {ts_str(profile.platform)},")
        lines.append(f"  ceremonyVersion: {profile.ceremony_version},")

        token = profile.token
        if token is None:
            lines.append("  token: null,")
        else:
            lines.append("  token: {")
            lines += ts_session(token, 4)
            lines += ts_array("requiredHeaders: ", required_headers(token), "    ", ",")
            lines += ts_array("tokenFields: ", token_fields(token), "    ", ",")
            lines.append("  },")

        identity = profile.identity
        if identity is None:
            lines.append("  identity: null,")
        else:
            lines.append("  identity: {")
            lines += ts_session(identity, 4)
            lines += ts_array("requiredHeaders: ", required_headers(identity), "    ", ",")
            lines.append(f"    idField: {ts_str(identity.id_field)},")
            lines.append(f"    idShape: {ts_str(identity.id_shape)},")
            lines.append(f"    handleField: {ts_str(identity.handle_field)},")
            lines.append("  },")
        lines += ["}", ""]

    names = ", ".join(upper(p.platform) for p in spec.profiles)
    lines += [
        "/** The launch profiles. */",
        f"export const LAUNCH: readonly Profile[] = [{names}]",
        "",
        "/** The launch profile for a platform name, or undefined. */",
        "export function launch(platform: string): Profile | undefined {",
        "  return LAUNCH.find((p) => p.platform === platform)",
        "}",
        "",
        "/** How many attestations a submission for this profile carries. */",
        "export function attestationCount(profile: Profile): number {",
        "  return (profile.token ? 1 : 0) + (profile.identity ? 1 : 0)",
        "}",
        "",
    ]
    lines += ts_doc(spec.requests.note)
    lines += ts_array(
        "export const FORBIDDEN_REQUEST_HEADERS: readonly string[] = ", forbidden_headers(spec), "", ""
    )
    lines.append("")
    lines += rust_doc(VALIDITY_NOTE, marker="//")
    for profile in spec.profiles:
        lines.append("")
        lines += rust_doc(profile.validity.note, marker="//")
        for const, value, bounds in validity_constants(profile):
            lines += ts_doc(f"`{profile.platform}/v{profile.ceremony_version}`: {bounds}")
            lines.append(f"export const {const} = {value}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Write nothing; exit non-zero if a generated file is stale.",
    )
    args = parser.parse_args()

    if not SOURCE.exists():
        print(f"ERROR: {SOURCE} is missing", file=sys.stderr)
        return 1
    if not PLATFORMS.exists():
        print(f"ERROR: {PLATFORMS_REL} is missing; run scripts/vendor-circuit-verifiers.sh", file=sys.stderr)
        return 1
    spec = Spec.from_json(
        json.loads(SOURCE.read_text(encoding="utf-8")),
        json.loads(PLATFORMS.read_text(encoding="utf-8")),
    )
    validate(spec)

    outputs = [(SOL_OUT, sol_formatted(gen_sol(spec)))]
    skipped = []
    for path, gen in ((RUST_OUT, gen_rust), (TS_OUT, gen_ts)):
        if path.parent.exists():
            outputs.append((path, gen(spec)))
        else:
            skipped.append(path)

    for path in skipped:
        print(
            f"note: skipping {path.relative_to(REPO_ROOT)} — "
            f"{path.parent.relative_to(REPO_ROOT)} does not exist yet"
        )

    if args.check:
        stale = [
            path
            for path, text in outputs
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            print(
                "ERROR: generated files are out of date. Run scripts/regen-ceremony-profiles.py",
                file=sys.stderr,
            )
            for path in stale:
                print(f"  {path.relative_to(REPO_ROOT)}", file=sys.stderr)
            return 1
        print("generated files are up to date")
        return 0

    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
