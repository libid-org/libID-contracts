def rust_doc(note: Note, indent: str = "", marker: str = "///") -> list[str]:
    return [f"{indent}{marker} {line}" if line else f"{indent}{marker}" for line in as_lines(note)]


def rust_str(value: str | None) -> str:
    if value is None:
        return "None"
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'Some("{escaped}")'


def rust_session(session: Session, indent: int) -> list[str]:
    pad = " " * indent
    return [
        f"{pad}session: Session {{",
        f'{pad}    authority: "{session.authority}",',
        f'{pad}    method: "{session.method}",',
        f'{pad}    path: "{session.path}",',
        f'{pad}    request_line: "{session.request_line}",',
        f"{pad}}},",
    ]


def rust_max_width() -> int:
    """rustfmt's line width, read from its own config so the two agree."""
    config = REPO_ROOT / "rust" / "rustfmt.toml"
    if not config.exists():
        return 100
    for line in config.read_text(encoding="utf-8").splitlines():
        key, _, rest = line.partition("=")
        if key.strip() == "max_width":
            return int(rest.split("#", 1)[0].strip())
    return 100


def rust_array(prefix: str, items: list[str], indent: str, suffix: str) -> list[str]:
    """`prefix&[items]suffix` on one line when it fits, else one item per line.

    rustfmt's rule, so a generated file passes `fmt --check` unformatted.
    """
    one = f"{indent}{prefix}&[{', '.join(f'\"{item}\"' for item in items)}]{suffix}"
    if len(one) <= rust_max_width():
        return [one]
    return [f"{indent}{prefix}&[", *(f'{indent}    "{item}",' for item in items), f"{indent}]{suffix}"]


def gen_rust(spec: Spec) -> str:
    lines = [header("//").rstrip("\n"), ""]
    lines += rust_doc(spec.note, marker="//!")
    lines += [
        "",
        "/// Which shape a platform's immutable identifier takes in its response.",
        "///",
        "/// A bare integer is revealed with its terminator, which proves the digits",
        "/// are the whole number (REQ-PLAT-51).",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub enum IdShape {",
        "    /// `\"id\":\"2244994945\"`.",
        "    JsonString,",
        "    /// `\"id\":583231,`",
        "    JsonInteger,",
        "}",
        "",
        "/// One notarized session: which server, and which request.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct Session {",
        "    /// The lowercase TLS server name the notary authenticates, with no",
        "    /// trailing dot, and the request's `Host` header. The verifier compares",
        "    /// its keccak256, `authorityId`, to the profile's pin (REQ-COMMON-21A).",
        "    pub authority: &'static str,",
        "    pub method: &'static str,",
        "    pub path: &'static str,",
        "    /// The request-line prefix the verifier compares byte for byte. The",
        "    /// trailing space stops `GET /user` from prefixing `GET /users/me`.",
        "    pub request_line: &'static str,",
        "}",
        "",
        "/// The token session: the OAuth exchange.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct TokenSession {",
        "    pub session: Session,",
        "    /// The header lines a Platform Verifier requires exactly once: `host`",
        "    /// and `content-type`, lowercased as on the wire. Other headers pass",
        "    /// unless `FORBIDDEN_REQUEST_HEADERS` names them. `content-length` is",
        "    /// absent: the HTTP client writes it and the verifier reads it.",
        "    pub required_headers: &'static [&'static str],",
        "    /// The body's form fields in serialization order. Verifiers require",
        "    /// exactly these names in this order, each once with a nonempty value.",
        "    /// GitHub's list is REQ-PLAT-61's and X's is REQ-PLAT-63's.",
        "    pub token_fields: &'static [&'static str],",
        "}",
        "",
        "/// The identity session: the authenticated read that names the account.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct IdentitySession {",
        "    pub session: Session,",
        "    /// The header lines a Platform Verifier requires exactly once: `host`.",
        "    pub required_headers: &'static [&'static str],",
        "    pub id_field: &'static str,",
        "    pub id_shape: IdShape,",
        "    pub handle_field: &'static str,",
        "}",
        "",
        "/// One platform's ceremony profile at one Platform Ceremony Version.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct Profile {",
        "    /// The platform name. `platformId` is its keccak256.",
        "    pub platform: &'static str,",
        "    /// The Platform Ceremony Version. Platform and version together name a",
        "    /// profile (REQ-PLAT-01).",
        "    pub ceremony_version: u16,",
        "    /// `None` where the profile notarizes nothing.",
        "    pub token: Option<TokenSession>,",
        "    pub identity: Option<IdentitySession>,",
        "}",
        "",
        "impl Profile {",
        "    /// How many attestations a submission for this profile carries, one per",
        "    /// session (REQ-COMMON-41).",
        "    pub const fn attestation_count(&self) -> u8 {",
        "        self.token.is_some() as u8 + self.identity.is_some() as u8",
        "    }",
        "}",
        "",
    ]

    for profile in spec.profiles:
        name = upper(profile.platform)
        lines += rust_doc(profile.note)
        lines.append(f"pub const {name}: Profile = Profile {{")
        lines.append(f'    platform: "{profile.platform}",')
        lines.append(f"    ceremony_version: {profile.ceremony_version},")

        token = profile.token
        if token is None:
            lines.append("    token: None,")
        else:
            lines.append("    token: Some(TokenSession {")
            lines += rust_session(token, 8)
            lines += rust_array("required_headers: ", required_headers(token), "        ", ",")
            lines += rust_array("token_fields: ", token_fields(token), "        ", ",")
            lines.append("    }),")

        identity = profile.identity
        if identity is None:
            lines.append("    identity: None,")
        else:
            shape = "JsonString" if identity.id_shape == "jsonString" else "JsonInteger"
            lines.append("    identity: Some(IdentitySession {")
            lines += rust_session(identity, 8)
            lines += rust_array("required_headers: ", required_headers(identity), "        ", ",")
            lines.append(f'        id_field: "{identity.id_field}",')
            lines.append(f"        id_shape: IdShape::{shape},")
            lines.append(f'        handle_field: "{identity.handle_field}",')
            lines.append("    }),")
        lines += ["};", ""]

    names = ", ".join(f"&{upper(p.platform)}" for p in spec.profiles)
    lines += [
        "/// The launch profiles. `CeremonyProfile.attestationCount` reverts on any",
        "/// other platform.",
        f"pub const LAUNCH: &[&Profile] = &[{names}];",
        "",
        "/// The launch profile for a platform name, or `None` if it has none.",
        "pub fn launch(platform: &str) -> Option<&'static Profile> {",
        "    LAUNCH.iter().copied().find(|p| p.platform == platform)",
        "}",
        "",
    ]
    lines += rust_doc(spec.requests.note)
    lines += rust_array("pub const FORBIDDEN_REQUEST_HEADERS: &[&str] = ", forbidden_headers(spec), "", ";")
    lines.append("")
    lines += rust_doc(VALIDITY_NOTE, marker="//")
    for profile in spec.profiles:
        lines.append("")
        lines += rust_doc(profile.validity.note, marker="//")
        for const, value, bounds in validity_constants(profile):
            lines += rust_doc(f"`{profile.platform}/v{profile.ceremony_version}`: {bounds}")
            lines.append(f"pub const {const}: u64 = {value};")
    lines.append("")
    return "\n".join(lines)


